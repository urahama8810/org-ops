/* ============================================================
   01b-structure.js  組織運営の共通ルール（定義データ）
   ------------------------------------------------------------
   この会社で共有する「決め方」「任せ方」「お金の使い方」の
   ものさしを、1か所にまとめたもの。

   考え方の中心は次の1行。

     任せきりでも、細かく縛るのでもなく、
     決めたことを、決めた手順で、続けて確認する。

   人の性格を変えようとするのではなく、
   誰がやっても同じ結果になる手順を用意する。それがこのアプリの役割。
   ============================================================ */

