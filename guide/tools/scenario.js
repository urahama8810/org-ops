function __emp(name){
  var l = DB.data.employees;
  for(var i=0;i<l.length;i++) if(l[i].name === name) return l[i].id;
  return '';
}
function __oooOf(name){
  var id = __emp(name);
  var r = DB.data.oneOnOnes.filter(function(o){ return o.employeeId === id; });
  return r.length ? r[r.length-1].id : '';
}
function __rec(coll, i){
  var l = DB.data[coll] || [];
  return l[i] ? l[i].id : '';
}
function __demo(view){
  buildDemoData(); DB.save();
  if(typeof setSeenIntro === 'function') setSeenIntro(true);
  currentView = view; render();
}
function __blank(view){
  DB.data = emptyData(); DB.save();
  if(typeof setSeenIntro === 'function') setSeenIntro(true);
  currentView = view; render();
}
/* 「わたしの画面」を、その人として開く */
function __me(name){
  buildDemoData(); DB.save();
  if(typeof setSeenIntro === 'function') setSeenIntro(true);
  if(typeof setMyEmpId === 'function') setMyEmpId(__emp(name));
  currentView = 'me'; render();
}
function __meBlank(){
  buildDemoData(); DB.save();
  if(typeof setSeenIntro === 'function') setSeenIntro(true);
  if(typeof setMyEmpId === 'function') setMyEmpId('');
  currentView = 'me'; render();
}

